/**
 * @param {string} lang
 * @param {string} text
 */
function applyPhrases(text, phrases) {
  let result = text;
  for (const [from, to] of phrases) {
    result = result.split(from).join(to);
  }
  return result;
}

/**
 * @param {string} lang
 * @param {string} english
 */
export function translateCookiePolicy(lang, english) {
  const phrases = COOKIE_PHRASES[lang];
  if (!phrases) return english;
  return applyPhrases(english, phrases);
}

/**
 * @param {string} lang
 * @param {string} english
 */
export function translatePrivacyPolicy(lang, english) {
  const phrases = PRIVACY_PHRASES[lang];
  if (!phrases) return english;
  return applyPhrases(english, phrases);
}
